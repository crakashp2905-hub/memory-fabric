"""Test whether approval bound to generated source prevents plan mutation reuse."""
from __future__ import annotations

import hashlib
import json
import subprocess
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "src"))

from memory_fabric import MemoryFabric  # noqa: E402
from memory_fabric.actions import (  # noqa: E402
    EXECUTED,
    REFUSED,
    ActionGate,
    ActionPolicy,
    ActionRequest,
    Approval,
    ToolRule,
    binding_digest,
)
from memory_fabric.service import MemoryService  # noqa: E402
from memory_fabric.tool_protocol import CodeModePlan, GovernedToolRuntime  # noqa: E402

APPROVED_SOURCE = 'dispatch(target="pump-7", setpoint=40)'
MUTATIONS = {
    "trailing_comment": APPROVED_SOURCE + "  # reviewed context changed",
    "leading_comment": "# generated by revised prompt\n" + APPROVED_SOURCE,
    "blank_prefix": "\n" + APPROVED_SOURCE,
    "keyword_order": 'dispatch(setpoint=40, target="pump-7")',
    "multiline": 'dispatch(\n    target="pump-7",\n    setpoint=40,\n)',
    "append_new_effect": APPROVED_SOURCE + '\ndispatch(target="pump-9", setpoint=40)',
    "duplicate_effect": APPROVED_SOURCE + "\n" + APPROVED_SOURCE,
    "semicolon_new_effect": APPROVED_SOURCE + '; dispatch(target="pump-10", setpoint=40)',
    "parenthesized_call": '(dispatch(target="pump-7", setpoint=40))',
    "alternate_spacing": 'dispatch ( target = "pump-7" ,setpoint = 40 )',
}


def _request(plan: CodeModePlan) -> ActionRequest:
    call = plan.calls[0]
    return ActionRequest(
        target=call.tool,
        parameters=dict(call.arguments),
        provenance={"code_mode_program_sha256": plan.source_digest or ""},
    )


def evaluate() -> dict[str, Any]:
    fabric = MemoryFabric(":memory:", auto_activate=True)
    service = MemoryService(fabric=fabric)
    try:
        service.register_agent("operator", key=b"n6-10-research-key", tenant_id="tenant-1")
        session = service.session(service.issue("operator"))
        evidence_id = fabric.remember("reviewer", "Pump dispatch safety reviewed.",
                                      tenant_id="tenant-1", scope="team")
        fabric.validate(evidence_id, actor="reviewer")
        certificate = fabric.certify("dispatch", [evidence_id], "operator",
                                     tenant_id="tenant-1")
        gate = ActionGate(fabric, ActionPolicy(
            tools={"dispatch": ToolRule("dispatch", requires_human_approval=True)},
            grants={"operator": frozenset({"dispatch"})},
            approvers=frozenset({"reviewer"}),
        ))
        effects: list[dict[str, Any]] = []
        runtime = GovernedToolRuntime(gate, {
            "dispatch": lambda **args: effects.append(args) or "dispatched",
        })
        approved_plan = CodeModePlan.parse(APPROVED_SOURCE)
        approved_request = _request(approved_plan)
        approval = Approval(
            "reviewer", certificate.digest(),
            binding=binding_digest("dispatch", "operator", "tenant-1",
                                   approved_request, certificate),
        )

        approved = approved_plan.execute(
            runtime, agent_id="operator", tenant_id="tenant-1", session=session,
            certificate=certificate, approval=approval,
        )[0]
        mutated_results: list[dict[str, Any]] = []
        baseline_binding_equal = True
        provenance_binding_changed = True
        for variant_id, source in MUTATIONS.items():
            mutated_plan = CodeModePlan.parse(source)
            call = mutated_plan.calls[0]
            if call.tool != "dispatch" or dict(call.arguments) != {
                    "target": "pump-7", "setpoint": 40}:
                raise AssertionError(f"{variant_id} changed first-call semantics")
            mutated = runtime.execute(
                call, agent_id="operator", tenant_id="tenant-1", session=session,
                certificate=certificate, approval=approval,
            )
            baseline_request = ActionRequest(target="dispatch", parameters=dict(call.arguments))
            plain_original = ActionRequest(target="dispatch",
                                           parameters=dict(approved_plan.calls[0].arguments))
            baseline_equal = binding_digest(
                "dispatch", "operator", "tenant-1", plain_original, certificate
            ) == binding_digest(
                "dispatch", "operator", "tenant-1", baseline_request, certificate
            )
            provenance_differs = binding_digest(
                "dispatch", "operator", "tenant-1", _request(approved_plan), certificate
            ) != binding_digest(
                "dispatch", "operator", "tenant-1", _request(mutated_plan), certificate
            )
            baseline_binding_equal &= baseline_equal
            provenance_binding_changed &= provenance_differs
            mutated_results.append({
                "variant_id": variant_id,
                "source_sha256": mutated_plan.source_digest,
                "first_call_arguments": dict(call.arguments),
                "outcome": mutated.outcome,
                "reason_codes": list(mutated.decision.reason_codes)
                if mutated.decision else [],
                "per_effect_key_differs": (call.idempotency_key
                                           != approved_plan.calls[0].idempotency_key),
                "ordinary_binding_equal": baseline_equal,
                "provenance_binding_changed": provenance_differs,
            })

        # Execute the exact same first action through an ordinary policy-wrapped
        # call, whose request binds parameters/evidence but has no source digest.
        plain_request = ActionRequest(target="dispatch",
                                      parameters=dict(approved_plan.calls[0].arguments))
        plain_approval = Approval(
            "reviewer", certificate.digest(),
            binding=binding_digest("dispatch", "operator", "tenant-1",
                                   plain_request, certificate),
        )
        baseline_effects: list[dict[str, Any]] = []
        baseline = gate.execute(
            "dispatch", "operator", lambda _key: baseline_effects.append(
                dict(plain_request.parameters)) or "dispatched",
            certificate, key="n6-10-simple-policy-baseline", tenant_id="tenant-1",
            session=session, request=plain_request, approval=plain_approval,
        )
        all_mutations_refused = all(
            row["outcome"] == REFUSED and "approval_invalid" in row["reason_codes"]
            for row in mutated_results
        )
        all_keys_distinct = all(row["per_effect_key_differs"] for row in mutated_results)
        report = {
            "schema": "memory-fabric-n6-10-generated-program-provenance/1",
            "task_id": "N6-10", "evidence_level": "INTERNAL_INTEGRATION",
            "acceptance_passed": (
                approved.outcome == EXECUTED
                and effects == [{"target": "pump-7", "setpoint": 40}]
                and len(mutated_results) == len(MUTATIONS)
                and all_mutations_refused and all_keys_distinct
                and baseline.outcome == EXECUTED
                and baseline_effects == [{"target": "pump-7", "setpoint": 40}]
                and baseline_binding_equal and provenance_binding_changed
            ),
            "hypothesis": {
                "id": "MF-N6-10-H1",
                "claim": "Binding human approval to the SHA-256 digest of the complete constrained generated program, in addition to each exact ActionRequest and evidence certificate, prevents source-mutated plans from reusing approval when their first effect has unchanged arguments.",
                "null": "A policy-wrapped exact tool request provides the same source-mutation detection as generated-program provenance binding.",
                "primary_outcome": "Changed source is refused before handler invocation while the exact approved source executes.",
                "secondary_outcome": "Baseline request/evidence binding remains equal across the source mutation because it contains no program digest.",
                "scope": "Deterministic local integration test; one fixed plan mutation; no model-generated programs or statistical generalization.",
            },
            "results": {
                "approved_program_sha256": approved_plan.source_digest,
                "approved_outcome": approved.outcome,
                "mutations_total": len(mutated_results),
                "mutations_refused": sum(row["outcome"] == REFUSED
                                          for row in mutated_results),
                "mutations_with_approval_invalid": sum(
                    "approval_invalid" in row["reason_codes"] for row in mutated_results),
                "mutated_programs": mutated_results,
                "handler_effects": effects,
                "simple_policy_baseline_outcome": baseline.outcome,
                "simple_policy_baseline_effects": baseline_effects,
                "ordinary_action_binding_equal": baseline_binding_equal,
                "provenance_binding_changed": provenance_binding_changed,
                "per_effect_keys_differ_for_all_mutations": all_keys_distinct,
            },
            "source": {"commit": subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT,
                                                    check=True, capture_output=True,
                                                    text=True).stdout.strip(),
                       "experiment_sha256": hashlib.sha256(
                           Path(__file__).read_bytes()).hexdigest()},
            "limitations": [
                "One deterministic source mutation and one tool effect are tested; this is not a broad adversarial benchmark or model study.",
                "Approval remains host-issued and the test uses an in-memory certificate; deployment policy and key custody are outside this experiment.",
                "Program provenance binds the exact source text, including comments and whitespace; semantically equivalent text requires fresh approval.",
            ],
        }
        return report
    finally:
        service.close()


if __name__ == "__main__":
    result = evaluate()
    (ROOT / "research" / "results" / "n6-10-generated-program-provenance.json").write_text(
        json.dumps(result, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"task_id": result["task_id"],
                      "acceptance_passed": result["acceptance_passed"],
                      "results": result["results"]}, indent=2))
