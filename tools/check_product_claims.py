"""Validate public claims against the capability maturity inventory."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
CAPABILITIES = ROOT / "product" / "capabilities.json"
MATURITY = ROOT / "product" / "capability_maturity.json"
CLAIMS = ROOT / "product" / "public_claims.json"
PAGE = ROOT / "docs" / "product" / "CAPABILITY_MATURITY.md"
STATUSES = {"implemented", "experimental", "simulated", "externally_unverified"}


def _load(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def maturity_rows() -> list[dict[str, str]]:
    base = _load(CAPABILITIES)
    overrides = _load(MATURITY)["overrides"]
    rows = []
    for capability in base["capabilities"]:
        old_status = capability["status"]
        default = {"available": "implemented", "experimental": "experimental",
                   "planned": "externally_unverified", "unsupported": "externally_unverified"}[old_status]
        override = overrides.get(capability["id"], {})
        rows.append({"id": capability["id"], "title": capability["title"],
                     "status": override.get("status", default),
                     "basis": override.get("basis", "; ".join(capability["limitations"]))})
    for capability_id, override in overrides.items():
        if capability_id not in {row["id"] for row in rows}:
            rows.append({"id": capability_id, "title": capability_id.replace(".", " "),
                         "status": override["status"], "basis": override["basis"]})
    return rows


def render() -> str:
    maturity = _load(MATURITY)
    lines = ["# Capability maturity", "",
             "Generated by `tools/check_product_claims.py`; keep statuses evidence-bound.", "",
             "| status | meaning |", "|---|---|"]
    lines.extend(f"| **{status}** | {meaning} |" for status, meaning in maturity["status_definitions"].items())
    lines += ["", "## Inventory", "", "| capability | status | basis and limits |", "|---|---|---|"]
    lines.extend(f"| `{row['id']}` — {row['title']} | **{row['status']}** | {row['basis']} |"
                 for row in maturity_rows())
    lines += ["", "## Public claims", "", "Approved wording is gated by `tools/check_product_claims.py`. "
              "Claims about simulated or externally unverified capabilities fail the documentation check.", "",
              "| claim | wording | qualification | evidence |", "|---|---|---|---|"]
    for claim in _load(CLAIMS)["claims"]:
        lines.append(f"| `{claim['id']}` | {claim['text']} | {claim['qualification']} | "
                     f"{', '.join(f'`{path}`' for path in claim['evidence'])} |")
    lines.append("")
    return "\n".join(lines)


def validate_claims() -> list[str]:
    base = _load(CAPABILITIES)
    known = {row["id"] for row in base["capabilities"]} | set(_load(MATURITY)["overrides"])
    statuses = {row["id"]: row["status"] for row in maturity_rows()}
    claims = _load(CLAIMS)["claims"]
    issues: list[str] = []
    ids = [claim.get("id") for claim in claims]
    if len(ids) != len(set(ids)):
        issues.append("public claim IDs must be unique")
    for claim in claims:
        claim_id = claim.get("id", "<missing>")
        references = claim.get("capabilities", [])
        if not claim.get("text") or not references:
            issues.append(f"{claim_id}: claim needs wording and capability references")
        if not claim.get("evidence") or not claim.get("qualification"):
            issues.append(f"{claim_id}: claim needs evidence and qualification")
        for capability_id in references:
            if capability_id not in known:
                issues.append(f"{claim_id}: unknown capability {capability_id}")
            elif statuses[capability_id] in {"simulated", "externally_unverified"}:
                issues.append(f"{claim_id}: cannot present {statuses[capability_id]} capability {capability_id} as an established public claim")
            if capability_id not in statuses:
                issues.append(f"{claim_id}: capability {capability_id} has no maturity status")
        for path in claim.get("evidence", []):
            if not (ROOT / path).is_file():
                issues.append(f"{claim_id}: missing evidence file {path}")
    return issues


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    issues = validate_claims()
    if issues:
        print("\n".join(issues))
        return 1
    expected = render()
    if args.check:
        if not PAGE.is_file() or PAGE.read_text(encoding="utf-8").replace("\r\n", "\n") != expected:
            print("docs/product/CAPABILITY_MATURITY.md is stale; run python tools/check_product_claims.py")
            return 1
        return 0
    PAGE.write_text(expected, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
